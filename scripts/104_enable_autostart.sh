#!/usr/bin/env bash
set -euo pipefail

MODE="${1:-move}"
WS_DIR="${M20PRO_WS:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
CONTROL_WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UNIT_SRC="${CONTROL_WS}/systemd/m20pro-real.service"
UNIT_DST="/etc/systemd/system/m20pro-real.service"
SOCKET_UNIT_SRC="${CONTROL_WS}/systemd/m20pro-dddmr-socket-source.service"
SOCKET_UNIT_DST="/etc/systemd/system/m20pro-dddmr-socket-source.service"
MOTION_UNIT_SRC="${CONTROL_WS}/systemd/m20pro-dddmr-motion-source.service"
MOTION_UNIT_DST="/etc/systemd/system/m20pro-dddmr-motion-source.service"
MOTION_2D_UNIT_SRC="${CONTROL_WS}/systemd/m20pro-2d-motion-source.service"
MOTION_2D_UNIT_DST="/etc/systemd/system/m20pro-2d-motion-source.service"
ENV_DST="/etc/default/m20pro-real"

if [[ "${EUID}" -ne 0 ]]; then
  echo "Run this script as root on 104 after su." >&2
  echo "Usage: ./scripts/104_enable_autostart.sh [move|shadow]" >&2
  exit 2
fi

case "${MODE}" in
  move|shadow) ;;
  *)
    echo "Usage: ./scripts/104_enable_autostart.sh [move|shadow]" >&2
    exit 2
    ;;
esac

if [[ ! -f "${UNIT_SRC}" ]]; then
  echo "systemd unit not found: ${UNIT_SRC}" >&2
  exit 1
fi
if [[ ! -f "${SOCKET_UNIT_SRC}" ]]; then
  echo "socket source unit not found: ${SOCKET_UNIT_SRC}" >&2
  exit 1
fi
if [[ ! -f "${MOTION_UNIT_SRC}" ]]; then
  echo "motion source unit not found: ${MOTION_UNIT_SRC}" >&2
  exit 1
fi
if [[ ! -f "${MOTION_2D_UNIT_SRC}" ]]; then
  echo "2D motion source unit not found: ${MOTION_2D_UNIT_SRC}" >&2
  exit 1
fi

DEFAULT_NAVIGATION_BACKEND="dddmr_3d"
DEFAULT_WORKSPACE_MODE="3d"
DEFAULT_ENABLE_DDDMR_BRIDGE="true"
DEFAULT_ENABLE_DDDMR_RUNTIME="false"
DEFAULT_DDDMR_RUNTIME_BACKEND="official"
DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP="false"
DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP_EXTENT_M="2.0"
DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP_SPACING_M="0.25"
DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP_HEIGHT_M="0.0"
DEFAULT_DDDMR_FIELD_TEST_MODE_SCRIPT="${WS_DIR}/scripts/104_dddmr_field_test_mode.sh"
DEFAULT_DDDMR_MAPPING_START_COMMAND=""
DEFAULT_DDDMR_MAPPING_FINISH_COMMAND=""
DEFAULT_DDDMR_MAPPING_CANCEL_COMMAND=""
DEFAULT_DDDMR_MAPPING_STATUS_COMMAND=""
DEFAULT_DDDMR_RUNTIME_DISTRO="foxy"
DEFAULT_DDDMR_RUNTIME_WS="${WS_DIR}"
DEFAULT_DDDMR_RUNTIME_SETUP="${WS_DIR}/install/setup.bash"
DEFAULT_DDDMR_MAPPING_PACKAGE="m20pro_bringup"
DEFAULT_DDDMR_MAPPING_LAUNCH="m20pro_lightning_mapping.launch.py"
DEFAULT_DDDMR_ALGORITHM_PACKAGE="lightning"
DEFAULT_DDDMR_MAP_ASSET_MANIFEST="/home/user/.m20pro_web/dddmr_map_assets.yaml"
if [[ "${MODE}" == "move" ]]; then
  DEFAULT_ENABLE_DDDMR_RUNTIME="true"
fi
EFFECTIVE_NAVIGATION_BACKEND="${M20PRO_NAVIGATION_BACKEND:-${DEFAULT_NAVIGATION_BACKEND}}"
EFFECTIVE_WORKSPACE_MODE="${M20PRO_WORKSPACE_MODE:-${DEFAULT_WORKSPACE_MODE}}"
case "${EFFECTIVE_WORKSPACE_MODE}" in
  2d|3d) ;;
  *)
    echo "invalid M20PRO_WORKSPACE_MODE=${EFFECTIVE_WORKSPACE_MODE}; expected 2d or 3d" >&2
    exit 2
    ;;
esac
if [[ "${EFFECTIVE_WORKSPACE_MODE}" == "2d" ]]; then
  DEFAULT_NAVIGATION_BACKEND="nav2_2d"
  DEFAULT_ENABLE_DDDMR_BRIDGE="false"
  DEFAULT_ENABLE_DDDMR_RUNTIME="false"
  DEFAULT_DDDMR_RUNTIME_BACKEND="none"
  DEFAULT_DDDMR_RUNTIME_WS=""
  DEFAULT_DDDMR_RUNTIME_SETUP=""
  DEFAULT_DDDMR_MAPPING_PACKAGE=""
  DEFAULT_DDDMR_MAPPING_LAUNCH=""
  DEFAULT_DDDMR_ALGORITHM_PACKAGE=""
  DEFAULT_DDDMR_FIELD_TEST_MODE_SCRIPT=""
  DEFAULT_DDDMR_MAP_ASSET_MANIFEST="/home/user/.m20pro_2d_web/map_assets.yaml"
  # Do not inherit stale 3D values from a long-lived root shell.
  M20PRO_NAVIGATION_BACKEND="nav2_2d"
  M20PRO_ENABLE_DDDMR_BRIDGE="false"
  M20PRO_ENABLE_DDDMR_RUNTIME="false"
  M20PRO_DDDMR_RUNTIME_BACKEND="none"
  M20PRO_ENABLE_DDDMR_SOCKET_BRIDGE="false"
  M20PRO_ENABLE_DDDMR_MAP_ASSETS="false"
  M20PRO_DDDMR_RUNTIME_WS=""
  M20PRO_DDDMR_RUNTIME_SETUP=""
  M20PRO_DDDMR_MAPPING_PACKAGE=""
  M20PRO_DDDMR_MAPPING_LAUNCH=""
  M20PRO_DDDMR_ALGORITHM_PACKAGE=""
  M20PRO_DDDMR_FIELD_TEST_MODE_SCRIPT=""
  M20PRO_DDDMR_MAPPING_START_COMMAND=""
  M20PRO_DDDMR_MAPPING_FINISH_COMMAND=""
  M20PRO_DDDMR_MAPPING_CANCEL_COMMAND=""
  M20PRO_DDDMR_MAPPING_STATUS_COMMAND=""
  EFFECTIVE_NAVIGATION_BACKEND="${M20PRO_NAVIGATION_BACKEND:-nav2_2d}"
fi
EFFECTIVE_DDDMR_RUNTIME_BACKEND="${M20PRO_DDDMR_RUNTIME_BACKEND:-${DEFAULT_DDDMR_RUNTIME_BACKEND}}"
if [[ "${EFFECTIVE_DDDMR_RUNTIME_BACKEND}" == "field_proxy" ]]; then
  DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP="true"
fi
if [[ "${MODE}" == "move" && "${EFFECTIVE_NAVIGATION_BACKEND}" == "dddmr_3d" ]]; then
  DEFAULT_DDDMR_MAPPING_START_COMMAND="${WS_DIR}/scripts/lightning_raw_mapping_control.sh start {floor}"
  DEFAULT_DDDMR_MAPPING_FINISH_COMMAND="${WS_DIR}/scripts/lightning_raw_mapping_control.sh finish {floor}"
  DEFAULT_DDDMR_MAPPING_CANCEL_COMMAND="${WS_DIR}/scripts/lightning_raw_mapping_control.sh cancel {floor}"
  DEFAULT_DDDMR_MAPPING_STATUS_COMMAND="${WS_DIR}/scripts/lightning_raw_mapping_control.sh status {floor}"
fi

install -m 0644 "${UNIT_SRC}" "${UNIT_DST}"
install -m 0644 "${SOCKET_UNIT_SRC}" "${SOCKET_UNIT_DST}"
install -m 0644 "${MOTION_UNIT_SRC}" "${MOTION_UNIT_DST}"
install -m 0644 "${MOTION_2D_UNIT_SRC}" "${MOTION_2D_UNIT_DST}"
cat >"${ENV_DST}" <<EOF
M20PRO_REAL_MODE=${MODE}
M20PRO_CONTROL_WS=${CONTROL_WS}
M20PRO_WS=${WS_DIR}
M20PRO_WORKSPACE_MODE=${EFFECTIVE_WORKSPACE_MODE}
M20PRO_2D_RVIZ=${M20PRO_2D_RVIZ:-false}
M20PRO_FASTDDS_PROFILE=${M20PRO_FASTDDS_PROFILE:-project_udp}
M20PRO_CLEAN_STALE_FASTDDS_SHM=${M20PRO_CLEAN_STALE_FASTDDS_SHM:-1}
M20PRO_SCAN_TOPIC=${M20PRO_SCAN_TOPIC:-/scan}
M20PRO_NAVIGATION_BACKEND=${M20PRO_NAVIGATION_BACKEND:-${DEFAULT_NAVIGATION_BACKEND}}
M20PRO_ENABLE_DDDMR_BRIDGE=${M20PRO_ENABLE_DDDMR_BRIDGE:-${DEFAULT_ENABLE_DDDMR_BRIDGE}}
M20PRO_ENABLE_DDDMR_RUNTIME=${M20PRO_ENABLE_DDDMR_RUNTIME:-${DEFAULT_ENABLE_DDDMR_RUNTIME}}
M20PRO_ENABLE_DDDMR_SOCKET_BRIDGE=${M20PRO_ENABLE_DDDMR_SOCKET_BRIDGE:-true}
M20PRO_DDDMR_SOCKET_CLOUD_PATH=${M20PRO_DDDMR_SOCKET_CLOUD_PATH:-/run/m20pro/dddmr_edge_cloud.sock}
M20PRO_ENABLE_DDDMR_MAP_ASSETS=${M20PRO_ENABLE_DDDMR_MAP_ASSETS:-}
M20PRO_DDDMR_MAP_ASSET_MANIFEST=${M20PRO_DDDMR_MAP_ASSET_MANIFEST:-${DEFAULT_DDDMR_MAP_ASSET_MANIFEST}}
M20PRO_DDDMR_MAP_ASSET_RELOAD_PERIOD_S=${M20PRO_DDDMR_MAP_ASSET_RELOAD_PERIOD_S:-1.0}
M20PRO_DDDMR_FIELD_TEST_FLAT_MAP=${M20PRO_DDDMR_FIELD_TEST_FLAT_MAP:-${DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP}}
M20PRO_DDDMR_FIELD_TEST_FLAT_MAP_EXTENT_M=${M20PRO_DDDMR_FIELD_TEST_FLAT_MAP_EXTENT_M:-${DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP_EXTENT_M}}
M20PRO_DDDMR_FIELD_TEST_FLAT_MAP_SPACING_M=${M20PRO_DDDMR_FIELD_TEST_FLAT_MAP_SPACING_M:-${DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP_SPACING_M}}
M20PRO_DDDMR_FIELD_TEST_FLAT_MAP_HEIGHT_M=${M20PRO_DDDMR_FIELD_TEST_FLAT_MAP_HEIGHT_M:-${DEFAULT_DDDMR_FIELD_TEST_FLAT_MAP_HEIGHT_M}}
M20PRO_DDDMR_FIELD_TEST_MODE_SCRIPT=${M20PRO_DDDMR_FIELD_TEST_MODE_SCRIPT:-${DEFAULT_DDDMR_FIELD_TEST_MODE_SCRIPT}}
M20PRO_DDDMR_MAPPING_HOST=${M20PRO_DDDMR_MAPPING_HOST:-localhost}
M20PRO_DDDMR_MAPPING_USER=${M20PRO_DDDMR_MAPPING_USER:-user}
# Mapping commands contain spaces and are sourced by systemd's EnvironmentFile
# and by recording/deployment scripts. Keep them one shell value when the file
# is sourced instead of allowing the action word to be executed as a command.
M20PRO_DDDMR_MAPPING_START_COMMAND='${M20PRO_DDDMR_MAPPING_START_COMMAND:-${DEFAULT_DDDMR_MAPPING_START_COMMAND}}'
M20PRO_DDDMR_MAPPING_FINISH_COMMAND='${M20PRO_DDDMR_MAPPING_FINISH_COMMAND:-${DEFAULT_DDDMR_MAPPING_FINISH_COMMAND}}'
M20PRO_DDDMR_MAPPING_CANCEL_COMMAND='${M20PRO_DDDMR_MAPPING_CANCEL_COMMAND:-${DEFAULT_DDDMR_MAPPING_CANCEL_COMMAND}}'
M20PRO_DDDMR_MAPPING_STATUS_COMMAND='${M20PRO_DDDMR_MAPPING_STATUS_COMMAND:-${DEFAULT_DDDMR_MAPPING_STATUS_COMMAND}}'
M20PRO_DDDMR_RUNTIME_WS=${M20PRO_DDDMR_RUNTIME_WS-${DEFAULT_DDDMR_RUNTIME_WS}}
M20PRO_DDDMR_RUNTIME_DISTRO=${M20PRO_DDDMR_RUNTIME_DISTRO:-${DEFAULT_DDDMR_RUNTIME_DISTRO}}
M20PRO_DDDMR_RUNTIME_SETUP=${M20PRO_DDDMR_RUNTIME_SETUP-${DEFAULT_DDDMR_RUNTIME_SETUP}}
M20PRO_DDDMR_MAPPING_PACKAGE=${M20PRO_DDDMR_MAPPING_PACKAGE:-${DEFAULT_DDDMR_MAPPING_PACKAGE}}
M20PRO_DDDMR_MAPPING_LAUNCH=${M20PRO_DDDMR_MAPPING_LAUNCH:-${DEFAULT_DDDMR_MAPPING_LAUNCH}}
M20PRO_DDDMR_ALGORITHM_PACKAGE=${M20PRO_DDDMR_ALGORITHM_PACKAGE:-${DEFAULT_DDDMR_ALGORITHM_PACKAGE}}
M20PRO_DDDMR_RUNTIME_BACKEND=${M20PRO_DDDMR_RUNTIME_BACKEND:-${DEFAULT_DDDMR_RUNTIME_BACKEND}}
M20PRO_LIGHTNING_MAPPING_WORK_DIR=${M20PRO_LIGHTNING_MAPPING_WORK_DIR:-/root/.m20pro_lightning_mapping/work}
M20PRO_LIGHTNING_GROUND_HEIGHT_M=${M20PRO_LIGHTNING_GROUND_HEIGHT_M:-0.35}
M20PRO_LIGHTNING_GROUND_LOWER_MARGIN_M=${M20PRO_LIGHTNING_GROUND_LOWER_MARGIN_M:-0.10}
M20PRO_ENABLE_INSPECTION=${M20PRO_ENABLE_INSPECTION:-false}
M20PRO_INSPECTION_BACKEND=${M20PRO_INSPECTION_BACKEND:-rknn}
M20PRO_INSPECTION_SOURCE_TYPE=${M20PRO_INSPECTION_SOURCE_TYPE:-rtsp}
M20PRO_INSPECTION_RTSP_URL=${M20PRO_INSPECTION_RTSP_URL:-rtsp://10.21.31.103:8554/video1}
M20PRO_INSPECTION_CAMERA_NAME=${M20PRO_INSPECTION_CAMERA_NAME:-front_wide}
M20PRO_INSPECTION_MODEL_PATH=${M20PRO_INSPECTION_MODEL_PATH:-${WS_DIR}/install/m20pro_inspection/share/m20pro_inspection/models/best_rk3588_fp16.rknn}
M20PRO_INSPECTION_CLASS_NAMES_PATH=${M20PRO_INSPECTION_CLASS_NAMES_PATH:-${WS_DIR}/install/m20pro_inspection/share/m20pro_inspection/models/labels_zh.txt}
M20PRO_ENABLE_RADAR_INSPECTION=${M20PRO_ENABLE_RADAR_INSPECTION:-false}
M20PRO_RADAR_BACKEND=${M20PRO_RADAR_BACKEND:-dry_run}
M20PRO_RADAR_SCAN_MODE=${M20PRO_RADAR_SCAN_MODE:-measuring}
M20PRO_RADAR_DEVICE_URL=${M20PRO_RADAR_DEVICE_URL:-http://192.168.107.72:8080}
M20PRO_RADAR_OUTPUT_DIR=${M20PRO_RADAR_OUTPUT_DIR:-/home/user/m20pro_radar_results}
M20PRO_RADAR_RELEASE_ON_ANALYSIS=${M20PRO_RADAR_RELEASE_ON_ANALYSIS:-true}
M20PRO_RADAR_START_RETRY_TIMEOUT_S=${M20PRO_RADAR_START_RETRY_TIMEOUT_S:-120.0}
M20PRO_RADAR_START_RETRY_INTERVAL_S=${M20PRO_RADAR_START_RETRY_INTERVAL_S:-5.0}
M20PRO_RADAR_RESULT_RETRY_COUNT=${M20PRO_RADAR_RESULT_RETRY_COUNT:-5}
M20PRO_RADAR_RESULT_RETRY_INTERVAL_S=${M20PRO_RADAR_RESULT_RETRY_INTERVAL_S:-2.0}
M20PRO_RADAR_QUERY_ERROR_TIMEOUT_S=${M20PRO_RADAR_QUERY_ERROR_TIMEOUT_S:-120.0}
EOF

systemctl daemon-reload
systemctl enable m20pro-real.service
systemctl enable m20pro-dddmr-socket-source.service
systemctl enable m20pro-dddmr-motion-source.service
systemctl enable m20pro-2d-motion-source.service

echo "[104_enable_autostart] installed and enabled m20pro-real.service"
echo "[104_enable_autostart] installed and enabled m20pro-dddmr-socket-source.service"
echo "[104_enable_autostart] installed and enabled m20pro-dddmr-motion-source.service"
echo "[104_enable_autostart] installed and enabled m20pro-2d-motion-source.service"
echo "[104_enable_autostart] mode=${MODE}"
echo "[104_enable_autostart] start now: systemctl start m20pro-real.service"
echo "[104_enable_autostart] status: ./scripts/104_autostart_status.sh"
